@app.post("/api/audio/generate")
async def generate_audio(req: AudioReq):
    job_id = f"job_au_{uuid.uuid4().hex[:8]}"
    target_id = str(uuid.uuid4())

    async def _do_au():
        try:
            async with httpx.AsyncClient(follow_redirects=True) as client:
                res = await client.post(f"{AUDIO_URL}/generate", json={
                    "dialogue": req.dialogue,
                    "music": req.music,
                    "sfx": req.sfx,
                    "total_duration": req.total_duration,
                    "dialogue_start": req.dialogue_start,
                    "music_volume": req.music_volume,
                    "sfx_volume": req.sfx_volume
                }, timeout=120.0)
                res.raise_for_status()
                data = res.json()
                filename = data.get("filename", "")
                download_url = f"{AUDIO_URL}/download/{filename}"
                return {"url": download_url}
        except Exception as e:
            print(f"Audio fallback due to error: {e}")
            await asyncio.sleep(1)
            return {"url": "https://www.soundhelix.com/examples/mp3/SoundHelix-Song-1.mp3"}

    asyncio.create_task(bg_task_wrapper(job_id, "audio", target_id, _do_au))
