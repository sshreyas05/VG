@app.post("/api/export")
async def export_film(req: ExportReq):
    job_id = f"exp_{uuid.uuid4().hex[:8]}"
    target_id = "export_scene"

    async def _do_exp():
        # Auto-discover clips if none provided from frontend
        clips_to_process = req.clips or []
        if not clips_to_process:
            # get all transition mp4s from outputs folder sorted by timestamp
            import glob
            files = glob.glob("outputs/tr_*.mp4")
            files.sort(key=os.path.getmtime)
            for file in files:
                clips_to_process.append(f"/{file.replace(chr(92), '/')}")

        if not clips_to_process:
            await asyncio.sleep(2)
            return {"url": "https://www.w3schools.com/html/mov_bbb.mp4", "download_url": "https://www.w3schools.com/html/mov_bbb.mp4"}
            
        list_file = os.path.join("outputs", f"concat_list_{job_id}.txt")
        final_video = os.path.join("outputs", f"final_export_{job_id}.mp4")
        
        with open(list_file, "w") as f:
            for clip_url in clips_to_process:
                # clip_url might be /outputs/tr_xxxx.mp4
                if "outputs/" in clip_url:
                    local_path = os.path.join("outputs", clip_url.split("outputs/")[-1])
                    if os.path.exists(local_path):
                        f.write(f"file '{os.path.abspath(local_path)}'\n")

        import subprocess
        print(f"Concatenating export to {final_video}")
        cmd = [FFMPEG_EXE, "-f", "concat", "-safe", "0", "-i", list_file, "-c", "copy", "-y", final_video]
        try:
            subprocess.run(cmd, check=True)
        finally:
            if os.path.exists(list_file):
                os.remove(list_file)
                
        # the Vite proxy expects /outputs prefix
        frontend_url = f"/outputs/final_export_{job_id}.mp4"
        return {"url": frontend_url, "download_url": frontend_url}

    asyncio.create_task(bg_task_wrapper(job_id, "export", target_id, _do_exp))
    return {"job_id": job_id}


@app.post("/api/generate_full")
async def generate_full(req: BrainEnhanceReq):
    job_id = f"job_full_{uuid.uuid4().hex[:8]}"
    target_id = str(uuid.uuid4())
    
    async def _do_gen():
        import e2e_pipeline
        loop = asyncio.get_running_loop()
        def on_progress(msg, progress):
            payload = json.dumps({
                "type": "job_update",
                "job_id": job_id,
                "status": "running",
                "progress": progress,
                "message": msg
            })
            asyncio.run_coroutine_threadsafe(manager.broadcast(payload), loop)
            
        final_video_path = await asyncio.to_thread(e2e_pipeline.run_e2e_pipeline, req.idea, req.duration, on_progress)
        if final_video_path and os.path.exists(final_video_path):
            import shutil
            fname = os.path.basename(final_video_path)
            shutil.copy(final_video_path, os.path.join("outputs", fname))
            url = f"/outputs/{fname}"
            return {"url": url, "download_url": url}
        raise Exception("E2E Pipeline failed to output a final video.")
        
    asyncio.create_task(bg_task_wrapper(job_id, "export", target_id, _do_gen))
    return {"job_id": job_id}

