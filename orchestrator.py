@app.post("/api/brain/enhance")
async def enhance_idea(req: BrainEnhanceReq):
    import asyncio
    from gemma_video_pipeline import generate_video_json
    
    loop = asyncio.get_running_loop()
    try:
        # Run the gemma generation in a background thread so we don't block the asyncio event loop
        result = await loop.run_in_executor(None, generate_video_json, req.idea, req.duration)
        
        if result and len(result) > 0:
            # We take the first scene since the frontend expects a single scene object
            return result[0]
        else:
            raise Exception("No scenes generated by Gemma.")
    except Exception as e:
        print(f"Error in enhance_idea: {e}")
        return {
            "description": f"Error cinematic rendition of: {req.idea}",
            "keyframe_prompt": f"Wide establishing shot. {req.idea}",
            "clips": [{"clip": 1, "transition_prompt": "Camera pans.", "music": "Drone", "sound_effect": "Wind"}],
            "dialogue_prompt": [{"clip": 1, "dialogue": "There was an error."}]
        }

@app.post("/api/keyframes/generate")
async def generate_keyframe(req: KeyframeReq):
    filename = f"kf_{uuid.uuid4().hex[:8]}.jpeg"
    filepath = os.path.join("outputs", filename)
    
    # We use a base image file to mutate
    init_img = "WhatsApp Image 2026-04-05 at 22.46.57.jpeg"
    with open(init_img, "rb") as f:
        img_data = f.read()

    try:
        async with httpx.AsyncClient(follow_redirects=True) as client:
            res = await client.post(
                FLUX_URL,
                data={"prompt": req.prompt, "num_inference_steps": req.steps, "width": req.width, "height": req.height},
                files={"image_file": (os.path.basename(init_img), img_data, "image/jpeg")},
                timeout=300.0
            )
            res.raise_for_status()
            with open(filepath, "wb") as f:
                f.write(res.content)
        return {"url": f"/outputs/{filename}", "job_id": f"kf_{uuid.uuid4().hex[:8]}"}
    except Exception as e:
        print(f"Keyframe API Error: {e}")
        return {"url": "https://images.unsplash.com/photo-1614730321146-b6fa6a46bcb4?q=80&w=832&auto=format&fit=crop", "job_id": f"kf_{uuid.uuid4().hex[:8]}"}

