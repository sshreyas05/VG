# ── HELPER FOREGROUND JOB BROADCASTER ──
async def bg_task_wrapper(job_id: str, target_type: str, target_id: str, coro, *args):
    """Wrapper to broadcast job status to all connected WebSockets."""
    await manager.broadcast(json.dumps({
        "type": "job_update",
        "job_id": job_id,
        "status": "running",
        "progress": 10,
        "message": f"Starting {target_type} generation..."
    }))
    try:
        result = await coro(*args)
        await manager.broadcast(json.dumps({
            "type": "job_complete",
            "job_id": job_id,
            "target_type": target_type,
            "target_id": target_id,
            "result": result
        }))
    except Exception as e:
        await manager.broadcast(json.dumps({
            "type": "job_error",
            "job_id": job_id,
            "target_type": target_type,
            "target_id": target_id,
            "error": str(e)
        }))

